"""Writes engine/ubo/THIRD-PARTY-CRATES.txt: every Rust crate in engine/ubo/Cargo.lock with its version, licence
expression, repository and the text of its licence files, as the licences of MIT, Apache-2.0, BSD and Unicode-3.0
require them to travel with the binary.

    python3 tools/ubo/crate-licences.py        (needs cargo and network on the first run, to fetch the crates)

Run it again after any change to Cargo.lock and commit the result. The package carries it in licenses/ad-blocker/.
"""
import json
import subprocess
import sys
from pathlib import Path

root = Path(__file__).resolve().parents[2]
ubo = root / "engine" / "ubo"
meta = json.loads(subprocess.check_output(["cargo", "metadata", "--locked", "--format-version", "1"], cwd=ubo, text=True))
pkgs = sorted((p for p in meta["packages"] if p["name"] != "wren-ubo"), key=lambda p: (p["name"], p["version"]))
out = ["Third-party Rust crates linked into or used to build libwren-ubo.so and the filter compiler.",
       "Generated by tools/ubo/crate-licences.py from engine/ubo/Cargo.lock. adblock is MPL-2.0 (source: the repository",
       "named below, unmodified). rustc-hash is a copy with one change (engine/ubo/vendor/README.md).", ""]
for p in pkgs:
    d = Path(p["manifest_path"]).parent
    out.append("=" * 78)
    out.append(f"{p['name']} {p['version']}  licence: {p.get('license') or 'see files'}")
    if p.get("repository"):
        out.append(f"source: {p['repository']}")
    files = sorted(f for f in d.iterdir() if f.is_file() and f.name.upper().startswith(("LICENSE", "LICENCE", "COPYING", "UNLICENSE", "NOTICE")))
    if not files:
        out.append("(no licence file in the crate; the licence is the expression above)")
    for f in files:
        out.append("-" * 78)
        out.append(f.name)
        out.append(f.read_text(encoding="utf-8", errors="replace").rstrip())
    out.append("")
(ubo / "THIRD-PARTY-CRATES.txt").write_text("\n".join(out) + "\n", encoding="utf-8", newline="\n")
print(f"{len(pkgs)} crates -> engine/ubo/THIRD-PARTY-CRATES.txt")
